const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(require('node:path').join(__dirname,'queue.html'),'utf8');
const match = html.match(/<script>([\s\S]*?)<\/script>/i);
assert.ok(match, 'inline queue controller exists');
const nodes = new Map();
const document = {getElementById(id){if(!nodes.has(id))nodes.set(id,{textContent:'',innerHTML:''});return nodes.get(id)}};
const sandbox = {document,Date,console,setInterval(){},fetch:async()=>({ok:true,json:async()=>({updated_utc:'2026-10-10T19:15:00Z',items:[]})})};
vm.runInNewContext(match[1],sandbox,{timeout:3000,filename:'queue-inline.js'});
const now=new Date().toISOString();
assert.equal(sandbox.mirrorFresh({updated_utc:now}),true);
assert.equal(sandbox.mirrorFresh({updated_utc:'2026-10-10T19:15:00Z'}),false);
assert.equal(sandbox.mirrorFresh({updated_utc:'not-a-date'}),false);
assert.equal(sandbox.truthfulStatus({status:'RUNNING'},true),'UNVERIFIED_ACTIVE');
assert.equal(sandbox.truthfulStatus({status:'ACTIVE_VERIFIED'},true),'UNVERIFIED_ACTIVE');
assert.equal(sandbox.truthfulStatus({status:'RUNNING'},false),'STALE_UNVERIFIED');
sandbox.render({updated_utc:'2026-10-10T19:15:00Z',items:[{id:'Q-1',status:'RUNNING',title:'Unverified example',lane:'CORE'},{id:'Q-2',status:'RETIRED',title:'Retired example'}]});
assert.match(nodes.get('stamp').textContent,/STALE ARCHIVE/);
assert.match(nodes.get('rows').innerHTML,/STALE_UNVERIFIED/);
assert.doesNotMatch(nodes.get('rows').innerHTML,/Retired example/);
sandbox.render({updated_utc:now,items:[{id:'Q-1',status:'RUNNING',title:'Worker claim',lane:'CORE'}]});
assert.match(nodes.get('rows').innerHTML,/UNVERIFIED_ACTIVE/);
console.log('queue truth regression: PASS (9 assertions)');
